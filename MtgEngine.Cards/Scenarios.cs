using System.Text.Json.Serialization;

namespace MtgEngine.Cards;

/// <summary>
/// A test as data: a board, a sequence of actions, and what must be true afterwards. A ruling,
/// a rulebook example, a bug report and a hand-written check all take this shape, and the
/// engine runs them all through the same runner.
/// </summary>
public sealed record Scenario(
    string Id,
    string Title,
    ScenarioSource Source,
    ScenarioSetup Setup,
    IReadOnlyList<ScenarioStep> Steps,
    IReadOnlyList<Expectation> Expect);

[JsonPolymorphic(TypeDiscriminatorPropertyName = "kind")]
[JsonDerivedType(typeof(RulingSource), nameof(RulingSource))]
[JsonDerivedType(typeof(RulebookExampleSource), nameof(RulebookExampleSource))]
[JsonDerivedType(typeof(ReportSource), nameof(ReportSource))]
[JsonDerivedType(typeof(GeneratedSource), nameof(GeneratedSource))]
[JsonDerivedType(typeof(HumanSource), nameof(HumanSource))]
public abstract record ScenarioSource;

/// <summary>A Scryfall ruling, quoted, on the card the scenario belongs to.</summary>
public sealed record RulingSource(string OracleId, string Comment, string? PublishedAt = null) : ScenarioSource;

/// <summary>An "Example:" paragraph from the Comprehensive Rules, by rule number.</summary>
public sealed record RulebookExampleSource(string Rule, string Text) : ScenarioSource;

/// <summary>A player's report from a game log position.</summary>
public sealed record ReportSource(string GameId, int EventIndex, string? Note = null) : ScenarioSource;

/// <summary>Generated by the pipeline from the definition itself: the smoke scenario.</summary>
public sealed record GeneratedSource(string Generator) : ScenarioSource;

public sealed record HumanSource(string By, string? Note = null) : ScenarioSource;

/// <summary>The board before the first step. Cards are named; the runner resolves names through the definition store.</summary>
public sealed record ScenarioSetup(
    IReadOnlyList<PlayerSetup> Players,
    string ActivePlayer,
    Step StartAt = Step.PrecombatMain,
    int Seed = 1,
    int Turn = 1);

public sealed record PlayerSetup(
    string Name,
    int Life = 20,
    IReadOnlyList<CardRef>? Battlefield = null,
    IReadOnlyList<CardRef>? Hand = null,
    IReadOnlyList<CardRef>? Library = null,
    IReadOnlyList<CardRef>? Graveyard = null,
    IReadOnlyList<CardRef>? Exile = null,
    IReadOnlyList<CardRef>? Command = null,
    string? ManaPool = null,
    IReadOnlyDictionary<string, int>? Counters = null);

/// <summary>A card placed by a scenario. <paramref name="Alias"/> is how steps and expectations refer to it when names repeat.</summary>
public sealed record CardRef(
    string Name,
    string? Alias = null,
    bool Tapped = false,
    IReadOnlyDictionary<string, int>? Counters = null,
    string? AttachedTo = null,
    int Damage = 0,
    bool SummoningSick = false,
    bool FaceDown = false);

/// <summary>One thing a player does, or the runner does for them.</summary>
[JsonPolymorphic(TypeDiscriminatorPropertyName = "kind")]
[JsonDerivedType(typeof(CastStep), nameof(CastStep))]
[JsonDerivedType(typeof(ActivateStep), nameof(ActivateStep))]
[JsonDerivedType(typeof(PlayLandStep), nameof(PlayLandStep))]
[JsonDerivedType(typeof(AttackStep), nameof(AttackStep))]
[JsonDerivedType(typeof(BlockStep), nameof(BlockStep))]
[JsonDerivedType(typeof(PassStep), nameof(PassStep))]
[JsonDerivedType(typeof(ResolveAllStep), nameof(ResolveAllStep))]
[JsonDerivedType(typeof(AnswerStep), nameof(AnswerStep))]
[JsonDerivedType(typeof(AdvanceToStep), nameof(AdvanceToStep))]
[JsonDerivedType(typeof(AddManaStep), nameof(AddManaStep))]
[JsonDerivedType(typeof(ExpectRefusedStep), nameof(ExpectRefusedStep))]
public abstract record ScenarioStep;

public sealed record CastStep(string Player, string Card, IReadOnlyList<string>? Targets = null, int? X = null, IReadOnlyList<int>? Modes = null, IReadOnlyList<string>? CostChoices = null, string? AlternativeCost = null) : ScenarioStep;

public sealed record ActivateStep(string Player, string Card, int AbilityIndex, IReadOnlyList<string>? Targets = null, int? X = null, IReadOnlyList<string>? CostChoices = null) : ScenarioStep;

public sealed record PlayLandStep(string Player, string Card) : ScenarioStep;

public sealed record AttackStep(string Player, IReadOnlyList<Attack> Attacks) : ScenarioStep;

public sealed record Attack(string Attacker, string Defender);

public sealed record BlockStep(string Player, IReadOnlyList<Block> Blocks) : ScenarioStep;

public sealed record Block(string Blocker, string Attacker);

public sealed record PassStep(string Player) : ScenarioStep;

/// <summary>Every player passes until the stack is empty.</summary>
public sealed record ResolveAllStep : ScenarioStep;

/// <summary>Answer the pending question: a choice's option ids, in order.</summary>
public sealed record AnswerStep(string Player, IReadOnlyList<string> Answer) : ScenarioStep;

public sealed record AdvanceToStep(Step Step, int? Turn = null) : ScenarioStep;

public sealed record AddManaStep(string Player, string Mana) : ScenarioStep;

/// <summary>The next step must be refused by the engine, with a reason containing the text.</summary>
public sealed record ExpectRefusedStep(ScenarioStep Attempt, string? ReasonContains = null) : ScenarioStep;

/// <summary>What must hold after the steps.</summary>
[JsonPolymorphic(TypeDiscriminatorPropertyName = "kind")]
[JsonDerivedType(typeof(InZone), nameof(InZone))]
[JsonDerivedType(typeof(Life), nameof(Life))]
[JsonDerivedType(typeof(PowerToughness), nameof(PowerToughness))]
[JsonDerivedType(typeof(CountersAre), nameof(CountersAre))]
[JsonDerivedType(typeof(TappedIs), nameof(TappedIs))]
[JsonDerivedType(typeof(ZoneCount), nameof(ZoneCount))]
[JsonDerivedType(typeof(StackEmpty), nameof(StackEmpty))]
[JsonDerivedType(typeof(GameOver), nameof(GameOver))]
[JsonDerivedType(typeof(ControlledBy), nameof(ControlledBy))]
[JsonDerivedType(typeof(HasKeywordNow), nameof(HasKeywordNow))]
[JsonDerivedType(typeof(TypesAre), nameof(TypesAre))]
[JsonDerivedType(typeof(PlayerCountersAre), nameof(PlayerCountersAre))]
[JsonDerivedType(typeof(EventLogged), nameof(EventLogged))]
public abstract record Expectation;

public sealed record InZone(string Card, Zone Zone, string? Owner = null) : Expectation;

public sealed record Life(string Player, int Value) : Expectation;

public sealed record PowerToughness(string Card, int Power, int Toughness) : Expectation;

public sealed record CountersAre(string Card, string Counter, int Count) : Expectation;

public sealed record TappedIs(string Card, bool Tapped) : Expectation;

public sealed record ZoneCount(string Player, Zone Zone, int Count) : Expectation;

public sealed record StackEmpty : Expectation;

public sealed record GameOver(string? Winner) : Expectation;

public sealed record ControlledBy(string Card, string Player) : Expectation;

public sealed record HasKeywordNow(string Card, KeywordKind Keyword, bool Value = true) : Expectation;

public sealed record TypesAre(string Card, CardType Types, IReadOnlyList<string>? Subtypes = null) : Expectation;

public sealed record PlayerCountersAre(string Player, string Counter, int Count) : Expectation;

/// <summary>An event of the given kind was logged, optionally mentioning a card.</summary>
public sealed record EventLogged(string EventKind, string? Card = null) : Expectation;

/// <summary>What the engine's runner reports for one scenario.</summary>
public sealed record ScenarioResult(string ScenarioId, bool Passed, IReadOnlyList<ExpectationResult> Results, string? Error = null, IReadOnlyList<string>? Log = null);

public sealed record ExpectationResult(Expectation Expectation, bool Passed, string? Actual = null);

/// <summary>The engine's side of the contract: run a scenario, report. Implemented in MtgEngine.Rules.</summary>
public interface IScenarioRunner
{
    ScenarioResult Run(Scenario scenario, CancellationToken ct = default);
}

/// <summary>Where the runner finds cards by name. Implemented over the card files.</summary>
public interface IDefinitionStore
{
    CardDefinition? ByName(string name);

    CardDefinition? ByOracleId(string oracleId);
}
