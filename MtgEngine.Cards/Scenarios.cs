using System.Text.Json.Serialization;

namespace MtgEngine.Cards;

/// <summary>
/// A test as data: a board, a sequence of actions, and what must be true afterwards. A ruling,
/// a rulebook example, a bug report and a hand-written check all take this shape, and the
/// engine runs them all through the same runner.
/// </summary>
public sealed record Scenario(
    string Id,
    string Title,
    ScenarioSource Source,
    ScenarioSetup Setup,
    IReadOnlyList<ScenarioStep> Steps,
    IReadOnlyList<Expectation> Expect);

[JsonPolymorphic(TypeDiscriminatorPropertyName = "kind")]
[JsonDerivedType(typeof(RulingSource), nameof(RulingSource))]
[JsonDerivedType(typeof(RulebookExampleSource), nameof(RulebookExampleSource))]
[JsonDerivedType(typeof(ReportSource), nameof(ReportSource))]
[JsonDerivedType(typeof(GeneratedSource), nameof(GeneratedSource))]
[JsonDerivedType(typeof(HumanSource), nameof(HumanSource))]
public abstract record ScenarioSource;

/// <summary>A Scryfall ruling, quoted, on the card the scenario belongs to.</summary>
public sealed record RulingSource(string OracleId, string Comment, string? PublishedAt = null) : ScenarioSource;

/// <summary>An "Example:" paragraph from the Comprehensive Rules, by rule number.</summary>
public sealed record RulebookExampleSource(string Rule, string Text) : ScenarioSource;

/// <summary>A player's report from a game log position.</summary>
public sealed record ReportSource(string GameId, int EventIndex, string? Note = null) : ScenarioSource;

/// <summary>Generated by the pipeline from the definition itself: the smoke scenario.</summary>
public sealed record GeneratedSource(string Generator) : ScenarioSource;

public sealed record HumanSource(string By, string? Note = null) : ScenarioSource;

/// <summary>
/// The board before the first step. Cards are named; the runner resolves names through the
/// definition store.
/// </summary>
/// <param name="AutoAnswer">
/// Who answers the questions the game stops to ask (CR 101.4). A scenario generated from the
/// definition — the smoke scenario — sets this true: it has never seen the game's objects, so it
/// cannot name an option id, and the runner answers every question with the first legal option,
/// recorded as a real <c>AnswerChoice</c> command so the log still replays. A hand-written
/// scenario leaves it false and answers itself with <c>AnswerStep</c>: the answer it picks
/// is usually the point of the test, and a runner that answered first-legal would erase it.
/// </param>
public sealed record ScenarioSetup(
    IReadOnlyList<PlayerSetup> Players,
    string ActivePlayer,
    Step StartAt = Step.PrecombatMain,
    int Seed = 1,
    int Turn = 1,
    bool AutoAnswer = false);

public sealed record PlayerSetup(
    string Name,
    int Life = 20,
    IReadOnlyList<CardRef>? Battlefield = null,
    IReadOnlyList<CardRef>? Hand = null,
    IReadOnlyList<CardRef>? Library = null,
    IReadOnlyList<CardRef>? Graveyard = null,
    IReadOnlyList<CardRef>? Exile = null,
    IReadOnlyList<CardRef>? Command = null,
    string? ManaPool = null,
    IReadOnlyDictionary<string, int>? Counters = null);

/// <summary>A card placed by a scenario. <paramref name="Alias"/> is how steps and expectations refer to it when names repeat.</summary>
public sealed record CardRef(
    string Name,
    string? Alias = null,
    bool Tapped = false,
    IReadOnlyDictionary<string, int>? Counters = null,
    string? AttachedTo = null,
    int Damage = 0,
    bool SummoningSick = false,
    bool FaceDown = false);

/// <summary>One thing a player does, or the runner does for them.</summary>
[JsonPolymorphic(TypeDiscriminatorPropertyName = "kind")]
[JsonDerivedType(typeof(CastStep), nameof(CastStep))]
[JsonDerivedType(typeof(ActivateStep), nameof(ActivateStep))]
[JsonDerivedType(typeof(PlayLandStep), nameof(PlayLandStep))]
[JsonDerivedType(typeof(AttackStep), nameof(AttackStep))]
[JsonDerivedType(typeof(BlockStep), nameof(BlockStep))]
[JsonDerivedType(typeof(PassStep), nameof(PassStep))]
[JsonDerivedType(typeof(ResolveAllStep), nameof(ResolveAllStep))]
[JsonDerivedType(typeof(AnswerStep), nameof(AnswerStep))]
[JsonDerivedType(typeof(AdvanceToStep), nameof(AdvanceToStep))]
[JsonDerivedType(typeof(AddManaStep), nameof(AddManaStep))]
[JsonDerivedType(typeof(TapForManaStep), nameof(TapForManaStep))]
[JsonDerivedType(typeof(ExpectRefusedStep), nameof(ExpectRefusedStep))]
public abstract record ScenarioStep;

/// <summary>
/// A player casts a card (CR 601.2). Cards, targets and cost objects are named by the alias the
/// setup gave them, or by card name where no name repeats.
/// </summary>
/// <param name="CostObjects">
/// The objects a printed cost eats, chosen as the spell is cast (CR 601.2c) and paid for at
/// CR 601.2h: the creature a "Sacrifice a creature" cost sacrifices, the cards an exile cost
/// exiles. Without them the engine has to guess, and refuses instead — "There are not enough
/// permanents to sacrifice" is the refusal a scenario gets for leaving this null.
/// </param>
public sealed record CastStep(
    string Player,
    string Card,
    IReadOnlyList<string>? Targets = null,
    int? X = null,
    IReadOnlyList<int>? Modes = null,
    IReadOnlyList<string>? CostChoices = null,
    string? AlternativeCost = null,
    IReadOnlyList<string>? CostObjects = null) : ScenarioStep;

/// <summary>
/// A player activates an ability (CR 602.2), by its index in the face's ability list.
/// </summary>
/// <param name="CostObjects">
/// The objects the activation cost eats, chosen at CR 602.2b and paid at CR 601.2h — the same
/// field, and the same reason, as <c>CastStep.CostObjects</c>.
/// </param>
/// <remarks>ManaColors: the colour chosen for each "add one mana of any color" the ability adds, one letter per mana in the order added ("W", "WU"), CR 608.2d; null chooses nothing.</remarks>
public sealed record ActivateStep(
    string Player,
    string Card,
    int AbilityIndex,
    IReadOnlyList<string>? Targets = null,
    int? X = null,
    IReadOnlyList<string>? CostChoices = null,
    IReadOnlyList<string>? CostObjects = null,
    string? ManaColors = null) : ScenarioStep;

public sealed record PlayLandStep(string Player, string Card) : ScenarioStep;

public sealed record AttackStep(string Player, IReadOnlyList<Attack> Attacks) : ScenarioStep;

public sealed record Attack(string Attacker, string Defender);

public sealed record BlockStep(string Player, IReadOnlyList<Block> Blocks) : ScenarioStep;

public sealed record Block(string Blocker, string Attacker);

public sealed record PassStep(string Player) : ScenarioStep;

/// <summary>Every player passes until the stack is empty.</summary>
public sealed record ResolveAllStep : ScenarioStep;

/// <summary>Answer the pending question: a choice's option ids, in order.</summary>
public sealed record AnswerStep(string Player, IReadOnlyList<string> Answer) : ScenarioStep;

public sealed record AdvanceToStep(Step Step, int? Turn = null) : ScenarioStep;

public sealed record AddManaStep(string Player, string Mana) : ScenarioStep;

/// <summary>
/// A permanent is tapped for mana: the runner activates a mana ability of it (CR 605.1a), which
/// resolves as it is activated and never uses the stack (CR 605.3b), so the permanent taps and the
/// mana it makes lands in a pool (CR 106.4). <see cref="AddManaStep"/> puts mana in a pool without
/// anything having been tapped for it, so a "whenever ... is tapped for mana" trigger never sees
/// it; this step is what such a card's scenario says instead.
/// </summary>
/// <param name="ManaColors">
/// As <see cref="ActivateStep.ManaColors"/>: the colour chosen for each "add one mana of any color"
/// the ability adds, one letter per mana in the order added, CR 608.2d. Null chooses nothing, which
/// is right for a land that prints its colour and refused for one that does not.
/// </param>
/// <param name="AbilityIndex">
/// Which mana ability, counted from zero over the permanent's mana abilities alone and not over
/// every ability it has: a permanent that prints two of them, or one whose mana ability carries a
/// rider the scenario means to see, is tapped for the one the scenario names (CR 605.3). Null names
/// the first, so a step written without it means what it meant before this parameter existed.
/// Abilities that are not mana abilities are not counted, so an activated ability between two mana
/// abilities does not move the number, and neither does an ability an effect grants the permanent.
/// </param>
[RuleRef("605.3")]
public sealed record TapForManaStep(string Player, string Card, string? ManaColors = null, int? AbilityIndex = null) : ScenarioStep;

/// <summary>The next step must be refused by the engine, with a reason containing the text.</summary>
public sealed record ExpectRefusedStep(ScenarioStep Attempt, string? ReasonContains = null) : ScenarioStep;

/// <summary>What must hold after the steps.</summary>
[JsonPolymorphic(TypeDiscriminatorPropertyName = "kind")]
[JsonDerivedType(typeof(InZone), nameof(InZone))]
[JsonDerivedType(typeof(Life), nameof(Life))]
[JsonDerivedType(typeof(PowerToughness), nameof(PowerToughness))]
[JsonDerivedType(typeof(CountersAre), nameof(CountersAre))]
[JsonDerivedType(typeof(TappedIs), nameof(TappedIs))]
[JsonDerivedType(typeof(ZoneCount), nameof(ZoneCount))]
[JsonDerivedType(typeof(StackEmpty), nameof(StackEmpty))]
[JsonDerivedType(typeof(GameOver), nameof(GameOver))]
[JsonDerivedType(typeof(ControlledBy), nameof(ControlledBy))]
[JsonDerivedType(typeof(HasKeywordNow), nameof(HasKeywordNow))]
[JsonDerivedType(typeof(TypesAre), nameof(TypesAre))]
[JsonDerivedType(typeof(PlayerCountersAre), nameof(PlayerCountersAre))]
[JsonDerivedType(typeof(ManaPoolIs), nameof(ManaPoolIs))]
[JsonDerivedType(typeof(AttachedToIs), nameof(AttachedToIs))]
[JsonDerivedType(typeof(EventLogged), nameof(EventLogged))]
[JsonDerivedType(typeof(Shuffled), nameof(Shuffled))]
[JsonDerivedType(typeof(PhasedOutIs), nameof(PhasedOutIs))]
public abstract record Expectation;

public sealed record InZone(string Card, Zone Zone, string? Owner = null) : Expectation;

public sealed record Life(string Player, int Value) : Expectation;

public sealed record PowerToughness(string Card, int Power, int Toughness) : Expectation;

public sealed record CountersAre(string Card, string Counter, int Count) : Expectation;

public sealed record TappedIs(string Card, bool Tapped) : Expectation;

public sealed record ZoneCount(string Player, Zone Zone, int Count) : Expectation;

public sealed record StackEmpty : Expectation;

public sealed record GameOver(string? Winner) : Expectation;

public sealed record ControlledBy(string Card, string Player) : Expectation;

public sealed record HasKeywordNow(string Card, KeywordKind Keyword, bool Value = true) : Expectation;

public sealed record TypesAre(string Card, CardType Types, IReadOnlyList<string>? Subtypes = null) : Expectation;

public sealed record PlayerCountersAre(string Player, string Counter, int Count) : Expectation;

/// <summary>
/// A player's mana pool holds exactly this mana (CR 106.4). Written the way a mana cost is —
/// <c>"{G}{G}"</c>, <c>"{2}{U}"</c> — and read as a total, not an order: a pool is a bag of
/// symbols, so the expectation compares what is in it and not how it got there. The empty string
/// is an empty pool. This is what a "add {G} to your mana pool" card should assert; the event it
/// logged says only that mana changed, which is true of a card that added the wrong colour.
/// </summary>
public sealed record ManaPoolIs(string Player, string Mana) : Expectation;

/// <summary>
/// One permanent is attached to another (CR 301.5, 303.4f): the Aura, Equipment or Fortification
/// named by <c>Card</c> is attached to the object named by <c>To</c>. This is what an Aura
/// scenario means; asserting the Aura is merely on the battlefield passes for a moment and then
/// stops, because CR 704.5m puts an unattached Aura into its owner's graveyard. Named for
/// <c>TappedIs</c> and not <c>AttachedTo</c>, which is the predicate a card's own filter
/// uses ("Auras attached to it"); one discriminator, one meaning.
/// </summary>
public sealed record AttachedToIs(string Card, string To) : Expectation;

/// <summary>An event of the given kind was logged, optionally mentioning a card.</summary>
public sealed record EventLogged(string EventKind, string? Card = null) : Expectation;

/// <summary>That player's library was shuffled during the scenario, CR 701.20: a reorder that says it was a shuffle, not any reorder.</summary>
[RuleRef("701.20")]
public sealed record Shuffled(string Player) : Expectation;

/// <summary>
/// One permanent's phased status, CR 702.26b: the named card is phased out (or, with
/// <c>PhasedOut</c> false, phased in). This is a <b>status</b> and not a zone — a permanent that
/// phases out stays on the battlefield and is only treated as though it does not exist — so it is
/// the one thing a phasing scenario can assert. <c>InZone(card, Battlefield)</c> is true before and
/// after and proves nothing; <c>InZone</c> naming any other zone is the opposite claim and the two
/// together are refused (L048). It is not <c>TappedIs</c>, the other status a permanent carries
/// (CR 110.5), and not <c>ControlledBy</c>: a phased-out permanent keeps its controller, which is
/// how CR 702.26a knows whose untap step phases it back in.
/// </summary>
[RuleRef("702.26b")]
public sealed record PhasedOutIs(string Card, bool PhasedOut = true) : Expectation;

/// <summary>What the engine's runner reports for one scenario.</summary>
public sealed record ScenarioResult(string ScenarioId, bool Passed, IReadOnlyList<ExpectationResult> Results, string? Error = null, IReadOnlyList<string>? Log = null);

public sealed record ExpectationResult(Expectation Expectation, bool Passed, string? Actual = null);

/// <summary>The engine's side of the contract: run a scenario, report. Implemented in MtgEngine.Rules.</summary>
public interface IScenarioRunner
{
    ScenarioResult Run(Scenario scenario, CancellationToken ct = default);
}

/// <summary>Where the runner finds cards by name. Implemented over the card files.</summary>
public interface IDefinitionStore
{
    CardDefinition? ByName(string name);

    CardDefinition? ByOracleId(string oracleId);

    /// <summary>
    /// Every card name this store knows, CR 201.3: the names a player may be asked to choose from
    /// when a card says "choose a card name" and prints no options. A store that cannot enumerate
    /// itself answers nothing, which is why the default is empty rather than a throw — the caller
    /// offering the choice has to cope with an empty list by asking the player to name a card
    /// freely, exactly as CR 201.3 has it. Order is not part of the contract; a caller that shows
    /// the list sorts it.
    /// </summary>
    IEnumerable<string> Names => [];
}
