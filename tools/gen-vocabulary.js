#!/usr/bin/env node
/**
 * Generates MtgEngine.Cards/Generated/KeywordKind.g.cs and KeywordAction.g.cs from the
 * Comprehensive Rules text: one enum member per rule in group 702 (keyword abilities) and
 * group 701 (keyword actions), each carrying the rule number that defines it.
 *
 * The identifier transform here must match VocabularyNames.ToIdentifier in C#; a test in
 * MtgEngine.Cards.Tests re-derives the enums from the parsed rulebook and compares.
 *
 * Usage: node tools/gen-vocabulary.js   (from the repo root)
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const rulesPath = path.join(root, 'MtgEngine.Api', 'Knowledge', 'comprehensive-rules.txt');
const outDir = path.join(root, 'MtgEngine.Cards', 'Generated');

function toIdentifier(name) {
  // "∞ (Infinity)" is the one rule whose name explains itself in parentheses; the symbol is the name.
  const text = name.replace(/\([^)]*\)/g, '').replace(/∞/g, 'Infinity');
  let id = '';
  let upperNext = true;
  for (const ch of text) {
    if (/[\p{L}\p{N}]/u.test(ch)) {
      id += upperNext ? ch.toUpperCase() : ch;
      upperNext = false;
    } else {
      upperNext = true;
    }
  }
  if (/^[0-9]/.test(id)) id = '_' + id;
  return id;
}

function members(group) {
  const re = new RegExp(`^${group}\\.(\\d+)\\. (.+)$`);
  const seen = new Set();
  const out = [];
  for (const raw of fs.readFileSync(rulesPath, 'utf8').split(/\r?\n/)) {
    const m = re.exec(raw.trim());
    if (!m || m[1] === '1') continue;
    const name = m[2].trim();
    const id = toIdentifier(name);
    if (seen.has(id)) continue; // the document lists each group twice: contents and body
    seen.add(id);
    out.push({ rule: `${group}.${m[1]}`, name, id });
  }
  return out;
}

function emit(enumName, summary, list) {
  const lines = [
    '// <auto-generated>',
    `//   Generated by tools/gen-vocabulary.js from MtgEngine.Api/Knowledge/comprehensive-rules.txt.`,
    '//   Do not edit by hand. Re-run the generator when the rules file is replaced.',
    '// </auto-generated>',
    '',
    'namespace MtgEngine.Cards;',
    '',
    `/// <summary>${summary}</summary>`,
    `public enum ${enumName}`,
    '{',
  ];
  for (const m of list) {
    lines.push(`    /// <summary>${m.name}</summary>`);
    lines.push(`    [RuleRef("${m.rule}")]`);
    lines.push(`    ${m.id},`);
    lines.push('');
  }
  if (lines[lines.length - 1] === '') lines.pop();
  lines.push('}');
  lines.push('');
  return lines.join('\r\n');
}

const abilities = members(702);
const actions = members(701);
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'KeywordKind.g.cs'),
  emit('KeywordKind', 'The keyword abilities of CR 702, one member per rule, in rule order.', abilities),
);
fs.writeFileSync(
  path.join(outDir, 'KeywordAction.g.cs'),
  emit('KeywordAction', 'The keyword actions of CR 701, one member per rule, in rule order.', actions),
);
console.log(`KeywordKind: ${abilities.length} members; KeywordAction: ${actions.length} members`);
