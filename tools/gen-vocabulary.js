#!/usr/bin/env node
/**
 * Generates MtgEngine.Cards/Generated/KeywordKind.g.cs, KeywordAction.g.cs,
 * CreatureTypes.g.cs and LandTypes.g.cs from the Comprehensive Rules text: one enum member per
 * rule in group 702 (keyword abilities) and group 701 (keyword actions), each carrying the rule
 * number that defines it, the creature-type list of CR 205.3m as a set, and the basic land types
 * of CR 205.3i as a set.
 *
 * The identifier transform here must match VocabularyNames.ToIdentifier in C#; a test in
 * MtgEngine.Cards.Tests re-derives the enums from the parsed rulebook and compares, and
 * another re-runs this generator into a temp directory and compares the files byte for byte.
 *
 * Usage: node tools/gen-vocabulary.js   (from the repo root)
 *        VOCAB_OUT_DIR=<dir> node tools/gen-vocabulary.js   (write elsewhere, for that test)
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const rulesPath = path.join(root, 'MtgEngine.Api', 'Knowledge', 'comprehensive-rules.txt');
const outDir = process.env.VOCAB_OUT_DIR || path.join(root, 'MtgEngine.Cards', 'Generated');

function toIdentifier(name) {
  // "∞ (Infinity)" is the one rule whose name explains itself in parentheses; the symbol is the name.
  const text = name.replace(/\([^)]*\)/g, '').replace(/∞/g, 'Infinity');
  let id = '';
  let upperNext = true;
  for (const ch of text) {
    if (/[\p{L}\p{N}]/u.test(ch)) {
      id += upperNext ? ch.toUpperCase() : ch;
      upperNext = false;
    } else {
      upperNext = true;
    }
  }
  if (/^[0-9]/.test(id)) id = '_' + id;
  return id;
}

function members(group) {
  const re = new RegExp(`^${group}\\.(\\d+)\\. (.+)$`);
  const seen = new Set();
  const out = [];
  for (const raw of fs.readFileSync(rulesPath, 'utf8').split(/\r?\n/)) {
    const m = re.exec(raw.trim());
    if (!m || m[1] === '1') continue;
    const name = m[2].trim();
    const id = toIdentifier(name);
    if (seen.has(id)) continue; // the document lists each group twice: contents and body
    seen.add(id);
    out.push({ rule: `${group}.${m[1]}`, name, id });
  }
  return out;
}

function emit(enumName, summary, list) {
  const lines = [
    '// <auto-generated>',
    `//   Generated by tools/gen-vocabulary.js from MtgEngine.Api/Knowledge/comprehensive-rules.txt.`,
    '//   Do not edit by hand. Re-run the generator when the rules file is replaced.',
    '// </auto-generated>',
    '',
    'namespace MtgEngine.Cards;',
    '',
    `/// <summary>${summary}</summary>`,
    `public enum ${enumName}`,
    '{',
  ];
  for (const m of list) {
    lines.push(`    /// <summary>${m.name}</summary>`);
    lines.push(`    [RuleRef("${m.rule}")]`);
    lines.push(`    ${m.id},`);
    lines.push('');
  }
  if (lines[lines.length - 1] === '') lines.pop();
  lines.push('}');
  lines.push('');
  return lines.join('\r\n');
}

/**
 * The creature types of CR 205.3m. The rule names them in prose — "One creature type is two
 * words long: Time Lord. All other creature types are one word long: Advisor, ..., and Zubera."
 * — so every "... long:" clause up to its full stop is a list of types, which is what is read
 * here rather than the count of words in any of them.
 */
function creatureTypes() {
  const line = fs
    .readFileSync(rulesPath, 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim())
    .find((l) => /^205\.3m\b/.test(l));
  if (!line) throw new Error('CR 205.3m not found in ' + rulesPath);

  const found = new Set();
  const clause = /long:\s*([^.]+)\./g;
  let m;
  while ((m = clause.exec(line)) !== null) {
    for (const part of m[1].split(',')) {
      const name = part.trim().replace(/^and\s+/i, '');
      if (name) found.add(name);
    }
  }
  if (found.size < 2) throw new Error('CR 205.3m listed no creature types; the rule was reworded: ' + line);

  // Ordinal, so the order is the same in every environment and a C# test can re-derive it.
  return [...found].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/**
 * The basic land types of CR 205.3i. The rule lists every land type and then names the basic ones
 * in a second sentence — "Of that list, Forest, Island, Mountain, Plains, and Swamp are the basic
 * land types." — so that clause is what is read here; the full land-type list is deliberately not
 * emitted, because nothing asks it and a set nobody reads drifts unnoticed.
 */
function basicLandTypes() {
  const line = fs
    .readFileSync(rulesPath, 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim())
    .find((l) => /^205\.3i\b/.test(l));
  if (!line) throw new Error('CR 205.3i not found in ' + rulesPath);

  const clause = /Of that list,\s*([^.]+?)\s+are the basic land types/.exec(line);
  if (!clause) throw new Error('CR 205.3i named no basic land types; the rule was reworded: ' + line);

  const found = new Set();
  for (const part of clause[1].split(',')) {
    const name = part.trim().replace(/^and\s+/i, '');
    if (name) found.add(name);
  }
  if (found.size !== 5) throw new Error(`CR 205.3i named ${found.size} basic land types, not five: ` + line);

  // Ordinal, so the order is the same in every environment and a C# test can re-derive it.
  return [...found].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function emitLandTypes(list) {
  const lines = [
    '// <auto-generated>',
    '//   Generated by tools/gen-vocabulary.js from MtgEngine.Api/Knowledge/comprehensive-rules.txt.',
    '//   Do not edit by hand. Re-run the generator when the rules file is replaced.',
    '// </auto-generated>',
    '',
    'using System.Collections.Frozen;',
    '',
    'namespace MtgEngine.Cards;',
    '',
    '/// <summary>',
    '/// The basic land types of CR 205.3i. This is rules data, not card data: the five words name',
    '/// land subtypes the rules define, and no card is named by reading them. A land with a basic',
    '/// land type need not be a basic land (CR 205.4a), which is why the question is asked here and',
    '/// not of the Basic supertype, and a new set reaches the engine by replacing the rules text and',
    '/// re-running the generator, never by an edit to C#.',
    '/// </summary>',
    '[RuleRef("205.3i")]',
    'public static class LandTypes',
    '{',
    `    /// <summary>Every basic land type CR 205.3i names (${list.length} of them), sorted, matched without regard to case.</summary>`,
    '    public static FrozenSet<string> Basic { get; } = new[]',
    '    {',
    ...list.map((name) => `        ${literal(name)},`),
    '    }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);',
    '',
    '    /// <summary>Is this subtype one of the basic land types of CR 205.3i?</summary>',
    '    public static bool IsBasicLandType(string subtype) => subtype is not null && Basic.Contains(subtype);',
    '}',
    '',
  ];
  return lines.join('\r\n');
}

/** A C# string literal in pure ASCII: two creature types carry a typographic apostrophe. */
function literal(text) {
  let out = '"';
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') out += '\\' + ch;
    else if (code < 0x20 || code > 0x7e) out += '\\u' + code.toString(16).toUpperCase().padStart(4, '0');
    else out += ch;
  }
  return out + '"';
}

function emitCreatureTypes(list) {
  const lines = [
    '// <auto-generated>',
    '//   Generated by tools/gen-vocabulary.js from MtgEngine.Api/Knowledge/comprehensive-rules.txt.',
    '//   Do not edit by hand. Re-run the generator when the rules file is replaced.',
    '// </auto-generated>',
    '',
    'using System.Collections.Frozen;',
    '',
    'namespace MtgEngine.Cards;',
    '',
    '/// <summary>',
    '/// The creature types of CR 205.3m, in the rule the game defines them in. This is rules data,',
    '/// not card data: no card is named here, and a new set reaches the engine by replacing the',
    '/// rules text and re-running the generator, never by an edit to C#.',
    '/// </summary>',
    '[RuleRef("205.3m")]',
    'public static partial class CreatureTypes',
    '{',
    `    /// <summary>Every creature type CR 205.3m lists (${list.length} of them), sorted, matched without regard to case.</summary>`,
    '    public static FrozenSet<string> All { get; } = new[]',
    '    {',
    ...list.map((name) => `        ${literal(name)},`),
    '    }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);',
    '',
    '    /// <summary>Is this subtype one of the creature types of CR 205.3m?</summary>',
    '    public static bool IsCreatureType(string subtype) => subtype is not null && All.Contains(subtype);',
    '}',
    '',
  ];
  return lines.join('\r\n');
}

const abilities = members(702);
const actions = members(701);
const creatures = creatureTypes();
const basicLands = basicLandTypes();
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'KeywordKind.g.cs'),
  emit('KeywordKind', 'The keyword abilities of CR 702, one member per rule, in rule order.', abilities),
);
fs.writeFileSync(
  path.join(outDir, 'KeywordAction.g.cs'),
  emit('KeywordAction', 'The keyword actions of CR 701, one member per rule, in rule order.', actions),
);
fs.writeFileSync(path.join(outDir, 'CreatureTypes.g.cs'), emitCreatureTypes(creatures));
fs.writeFileSync(path.join(outDir, 'LandTypes.g.cs'), emitLandTypes(basicLands));
console.log(
  `KeywordKind: ${abilities.length} members; KeywordAction: ${actions.length} members; ` +
    `CreatureTypes: ${creatures.length} types; LandTypes: ${basicLands.length} basic types`,
);
